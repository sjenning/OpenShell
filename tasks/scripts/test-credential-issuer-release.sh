# Execute the release action's actual shell with a fake OCI client. Verify all
# image workflow permissions, chart identities, metadata, SHA-pinning, immutable
# reruns, and partial failures without registry writes. Requires Helm and yq.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
cd "${ROOT}"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
images=.github/workflows/build-images.yml
# Same-run artifact downloads use the Actions runtime artifact service, not a
# GITHUB_TOKEN-authenticated cross-run API request. Keep that contract explicit
# so the issuer smoke job needs no new permission from existing callers.
yq e -e '.jobs."smoke-credential-issuer".needs == "credential-issuer"' "${images}" >/dev/null
yq e -e '.jobs."smoke-credential-issuer".steps[] | select(.name == "Download candidate image archive") |
  ((.uses | test("^actions/download-artifact@")) and
  (.with.name == "image-credential-issuer") and (.with.path == "artifacts") and
  (.with.github-token == null) and (.with.run-id == null) and (.with.repository == null))' "${images}" >/dev/null
for caller in branch-e2e release-dev release-build; do
  yq e -o=json -I=0 '.jobs[] | select(.uses == "./.github/workflows/build-images.yml") | .permissions' \
    ".github/workflows/${caller}.yml" >"${work}/caller-permissions.json"
  [[ "$(wc -l <"${work}/caller-permissions.json" | tr -d ' ')" == 1 ]]
  # Check every explicit workflow/job request, not only the new smoke job.
  while IFS=$'\t' read -r permission requested; do
    granted="$(PERMISSION="${permission}" yq e -r '.[strenv(PERMISSION)] // "none"' "${work}/caller-permissions.json")"
    case "${requested}:${granted}" in
      none:*|read:read|read:write|write:write) ;;
      *) echo "FAIL: build-images requests ${permission}:${requested}, but ${caller} grants ${granted}" >&2; exit 1 ;;
    esac
  done < <(yq e -r '[.permissions, .jobs[].permissions] | .[] | select(. != null) | to_entries | .[] | [.key, .value] | @tsv' "${images}")
done
action=.github/actions/release-helm-oci/action.yml
export RUNNER_TEMP="${work}/runner" GITHUB_OUTPUT="${work}/outputs"
export CHART_VERSION=1.2.3 APP_VERSION=1.2.3 PIN_SHA=0123456789abcdef0123456789abcdef01234567
mkdir -p "${RUNNER_TEMP}"
yq e -r '.runs.steps[] | select(.id == "prep") | .run' "${action}" >"${work}/prep.sh"
bash "${work}/prep.sh"
# Outputs are paths generated by our action, never user or remote input.
export GATEWAY_CHART_DIR="$(sed -n 's/^gateway_chart_dir=//p' "${GITHUB_OUTPUT}")"
export WORKSPACE_CHART_DIR="$(sed -n 's/^workspace_chart_dir=//p' "${GITHUB_OUTPUT}")"
export ISSUER_CHART_DIR="$(sed -n 's/^issuer_chart_dir=//p' "${GITHUB_OUTPUT}")"
for directory in "${GATEWAY_CHART_DIR}" "${WORKSPACE_CHART_DIR}" "${ISSUER_CHART_DIR}"; do
  [[ "$(yq e '.version' "${directory}/Chart.yaml")" == "${CHART_VERSION}" ]]
  [[ "$(yq e '.appVersion' "${directory}/Chart.yaml")" == "${APP_VERSION}" ]]
done
# Isolate the action's temporary paths rather than touching shared /tmp output.
yq e -r '.runs.steps[] | select(.name == "Package Helm chart") | .run' "${action}" \
  | sed "s|/tmp/helm-charts|${work}/archives|g" >"${work}/package.sh"
bash "${work}/package.sh" >/dev/null
for chart in helm-chart openshell-workspace openshell-credential-issuer; do
  test -f "${work}/archives/${chart}-${CHART_VERSION}.tgz"
done
[[ "$(find "${work}/archives" -name '*.tgz' | wc -l | tr -d ' ')" == 3 ]]
REAL_HELM="$(command -v helm)"; export REAL_HELM
export PUSH_LOG="${work}/pushes" LOOKUP_MODE=none
# shellcheck disable=SC2329 # Called by the action shell via export -f.
helm() {
  if [[ "$1" == show ]]; then
    case "${LOOKUP_MODE}" in
      all) return 0 ;;
      partial) [[ "$3" == */helm-chart ]] && return 0 ;;
      error) echo 'registry authentication unavailable' >&2; return 1 ;;
    esac
    echo "${3#oci://}:${5}: not found" >&2
    return 1
  fi
  if [[ "$1" == push ]]; then
    printf '%s\n' "$2" >>"${PUSH_LOG}"
    return 0
  fi
  "${REAL_HELM}" "$@"
}
export -f helm
yq e -r '.runs.steps[] | select(.id == "published") | .run' "${action}" >"${work}/lookup.sh"
bash "${work}/lookup.sh"
LOOKUP_MODE=all bash "${work}/lookup.sh"
grep -x 'published=true' "${GITHUB_OUTPUT}" >/dev/null
if LOOKUP_MODE=partial bash "${work}/lookup.sh" >"${work}/error" 2>&1; then
  echo 'FAIL: partial chart publication was accepted' >&2; exit 1
fi
if LOOKUP_MODE=error bash "${work}/lookup.sh" >"${work}/error" 2>&1; then
  echo 'FAIL: registry lookup failure was treated as unpublished' >&2; exit 1
fi
yq e -r '.runs.steps[] | select(.name == "Push Helm chart to GHCR OCI") | .run' "${action}" \
  | sed "s|/tmp/helm-charts|${work}/archives|g" >"${work}/push.sh"
bash "${work}/push.sh"
[[ "$(wc -l <"${PUSH_LOG}" | tr -d ' ')" == 3 ]]
yq e -r '.runs.steps[] | select(.name == "Push SHA-pinned chart") | .run' "${action}" \
  | sed "s|/tmp/sha-pin|${work}/sha-pin|g" >"${work}/sha.sh"
bash "${work}/sha.sh" >/dev/null
[[ "$(wc -l <"${PUSH_LOG}" | tr -d ' ')" == 6 ]]
for chart in helm-chart openshell-workspace openshell-credential-issuer; do
  archive="${work}/sha-pin/${chart}-0.0.0-dev.${PIN_SHA}.tgz"
  test -f "${archive}"
  [[ "$("${REAL_HELM}" show chart "${archive}" | yq e '.appVersion')" == "${PIN_SHA}" ]]
done
echo 'issuer image workflow permissions, release chart packaging, immutable rerun/partial failure guards, and SHA-pinned publication passed (no registry writes)'
